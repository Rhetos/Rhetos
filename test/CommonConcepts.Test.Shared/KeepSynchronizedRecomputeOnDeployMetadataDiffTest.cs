using System;
using System.Collections.Generic;
using System.Linq;
using Microsoft.VisualStudio.TestTools.UnitTesting;
using Rhetos;
using Rhetos.Dom.DefaultConcepts;

namespace CommonConcepts.Test
{
    [TestClass]
    public class KeepSynchronizedRecomputeOnDeployMetadataDiffTest
    {
        [TestMethod]
        public void Metadata_without_target_computed_properties_is_detected_as_changed()
        {
            using IUnitOfWorkScope scope = TestScope.Create();

            // This test checks metadata differences only; it does not run the deployment initializer or recompute data.
            // Read the metadata persisted by the currently deployed test app.
            GenericRepositories repos = scope.Resolve<GenericRepositories>();
            IKeepSynchronizedMetadata persisted = repos.GetGenericRepository<IKeepSynchronizedMetadata>()
                .Load()
                .FirstOrDefault(m => m.Source == "TestComputedFrom.Source");

            Assert.IsNotNull(persisted, "Expected a KeepSynchronizedMetadata row for TestComputedFrom.Source to exist in the database.");

            // Verify that the deployed metadata includes the target-property mapping suffix.
            StringAssert.Contains(persisted.Context, "TargetComputedProperties");

            // Read the in-memory metadata generated by the current DSL.
            IKeepSynchronizedMetadata current = scope.Resolve<CurrentKeepSynchronizedMetadata>()
                .FirstOrDefault(m => m.Source == "TestComputedFrom.Source");

            Assert.IsNotNull(current);

            // Simulate the older context format: same Source/Target, but no target-property mapping suffix.
            TestKeepSynchronizedMetadata stale = new TestKeepSynchronizedMetadata
            {
                Target = persisted.Target,
                Source = persisted.Source,
                Context = StripTargetComputedProperties(persisted.Context)
            };

            // Compare the simulated old-format metadata with the current generated metadata.
            DiffResult<IKeepSynchronizedMetadata> diff = ComputedFromHelper.Diff(
                new List<IKeepSynchronizedMetadata> { stale },
                new List<IKeepSynchronizedMetadata> { current },
                new ComputationKeyComparer(),
                (x, y) => x.Source == y.Source && x.Target == y.Target && x.Context == y.Context);

            Assert.HasCount(1, diff.ToUpdate, "Comparing the old context format with the current format should produce one metadata update.");

            // Comparing unchanged metadata should produce no updates.
            DiffResult<IKeepSynchronizedMetadata> diffNoChange = ComputedFromHelper.Diff(
                new List<IKeepSynchronizedMetadata> { current },
                new List<IKeepSynchronizedMetadata> { current },
                new ComputationKeyComparer(),
                (x, y) => x.Source == y.Source && x.Target == y.Target && x.Context == y.Context);

            Assert.IsEmpty(diffNoChange.ToUpdate);
        }

        private static string StripTargetComputedProperties(string context)
        {
            string marker = " | TargetComputedProperties";
            int index = context.IndexOf(marker, StringComparison.Ordinal);
            return index < 0 ? context : context.Substring(0, index);
        }

        private sealed class TestKeepSynchronizedMetadata : IKeepSynchronizedMetadata
        {
            public Guid ID { get; set; }
            public string Target { get; set; }
            public string Source { get; set; }
            public string Context { get; set; }
        }

        private sealed class ComputationKeyComparer : IComparer<IKeepSynchronizedMetadata>
        {
            public int Compare(IKeepSynchronizedMetadata x, IKeepSynchronizedMetadata y)
            {
                return string.Compare(GetKey(x), GetKey(y), StringComparison.Ordinal);
            }

            private static string GetKey(IKeepSynchronizedMetadata ks) => ks.Source + "/" + ks.Target;
        }
    }
}
